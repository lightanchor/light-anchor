    /// dsh 行的成品图标：DeepSeek 鲸标（透明底 glyph）合成到白色圆角砖上，
    /// 这正是 DeepSeek 自家应用图标的样子。白砖在白卡片上会隐形，
    /// 描一圈发丝边让它和邻居一样读作图标砖。
    static func deepseekTileImage() -> NSImage? {
        guard let whale = NSImage(data: Data(deepseekWhaleSVG.utf8)) else { return nil }
        let side: CGFloat = 128
        let image = NSImage(size: NSSize(width: side, height: side))
        image.lockFocus()
        let hairline: CGFloat = 1
        let tile = NSBezierPath(
            roundedRect: NSRect(
                x: hairline / 2, y: hairline / 2,
                width: side - hairline, height: side - hairline
            ),
            xRadius: side * 0.24,
            yRadius: side * 0.24
        )
        NSColor.white.setFill()
        tile.fill()
        NSColor.black.withAlphaComponent(0.12).setStroke()
        tile.lineWidth = hairline
        tile.stroke()
        let inset = side * 0.14
        whale.draw(in: NSRect(x: inset, y: inset, width: side - inset * 2, height: side - inset * 2))
        image.unlockFocus()
        return image
    }

    /// pi 行的成品图标：官方 favicon 自带黑砖底，直接矢量渲染。
